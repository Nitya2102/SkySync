"""Orchestrator for the six-agent coexistence pipeline with SSE streaming and audit logging."""
from __future__ import annotations

import asyncio
import json
import logging
import time
import uuid
from pathlib import Path
from typing import Any, AsyncGenerator, Optional

from app.agents.airspace_safety import AirspaceSafetyAgent
from app.agents.arbitration import ArbitrationAgent
from app.agents.network import NetworkAgent
from app.agents.optimization import OptimizationAgent
from app.agents.policy import PolicyInstitutionalAgent
from app.agents.spectrum import SpectrumAgent
from app.config import RUNS_DIR
from app.models import (
    AgentReport,
    ArbitrationReport,
    CandidateAction,
    RunResult,
    SimulationState,
)

logger = logging.getLogger(__name__)


class Orchestrator:
    """Coordinates execution across all 6 agents, collects results, streams SSE, and logs runs."""

    def __init__(self):
        self.network_agent = NetworkAgent()
        self.airspace_agent = AirspaceSafetyAgent()
        self.spectrum_agent = SpectrumAgent()
        self.policy_agent = PolicyInstitutionalAgent()
        self.opt_agent = OptimizationAgent()
        self.arb_agent = ArbitrationAgent()

    async def run_pipeline(
        self,
        state: SimulationState,
        candidate_actions: list[CandidateAction],
        as_of: str = "2026-10-07",
        run_id: Optional[str] = None,
        scenario_id: Optional[str] = None,
    ) -> RunResult:
        """Execute complete 2-phase pipeline synchronously/async without SSE."""
        run_id = run_id or f"run_{uuid.uuid4().hex[:8]}"
        scenario_id = scenario_id or self._infer_scenario_id(state)
        start_t = time.time()

        # Phase 1: Run 4 domain agents concurrently
        p1_tasks = [
            self.network_agent.run(state, as_of),
            self.airspace_agent.run(state, as_of),
            self.spectrum_agent.run(state, as_of),
            self.policy_agent.run(state, as_of),
        ]
        p1_results = await asyncio.gather(*p1_tasks, return_exceptions=True)

        agent_reports: dict[str, AgentReport] = {}
        names = ["network", "airspace_safety", "spectrum", "policy_institutional"]
        for name, res in zip(names, p1_results):
            if isinstance(res, Exception):
                logger.error("Phase 1 agent %s failed with exception: %s", name, res)
                # Build fallback report
                agent_reports[name] = AgentReport(
                    agent_name=name,
                    error=str(res),
                    warnings=[f"Agent execution exception: {res}"],
                    confidence=0.1,
                )
            else:
                agent_reports[name] = res

        # Merge candidate actions generated by domain agents into candidate pool
        all_candidate_actions = list(candidate_actions)
        seen_action_ids = {a.id for a in all_candidate_actions}
        for rep in agent_reports.values():
            for act in rep.candidate_actions:
                if act.id not in seen_action_ids:
                    all_candidate_actions.append(act)
                    seen_action_ids.add(act.id)
                else:
                    self._merge_action_metadata(all_candidate_actions, act)

        # Phase 2: Run OptimizationAgent
        try:
            opt_report = await self.opt_agent.run(state, as_of)
            agent_reports["optimization"] = opt_report
            for act in opt_report.candidate_actions:
                if act.id not in seen_action_ids:
                    all_candidate_actions.append(act)
                    seen_action_ids.add(act.id)
                else:
                    self._merge_action_metadata(all_candidate_actions, act)
        except Exception as e:
            logger.error("Optimization agent failed: %s", e)
            agent_reports["optimization"] = AgentReport(
                agent_name="optimization", error=str(e), confidence=0.1
            )

        # Phase 3: Run ArbitrationAgent
        arb_report = await self.arb_agent.arbitrate(
            state=state,
            candidate_actions=all_candidate_actions,
            agent_reports=agent_reports,
            as_of=as_of,
        )

        total_latency = time.time() - start_t

        result = RunResult(
            run_id=run_id,
            scenario_id=scenario_id,
            as_of=as_of,
            simulation_state=state,
            agent_reports=agent_reports,
            arbitration=arb_report,
            candidate_actions=all_candidate_actions,
            total_latency_s=round(total_latency, 3),
        )

        # Audit log to runs/{run_id}.json
        self._write_audit_log(result)
        return result

    async def stream_pipeline(
        self,
        state: SimulationState,
        candidate_actions: list[CandidateAction],
        as_of: str = "2026-10-07",
        run_id: Optional[str] = None,
        scenario_id: Optional[str] = None,
    ) -> AsyncGenerator[str, None]:
        """Stream SSE events during execution."""
        run_id = run_id or f"run_{uuid.uuid4().hex[:8]}"
        scenario_id = scenario_id or self._infer_scenario_id(state)
        start_t = time.time()

        def sse_msg(event: str, data: Any) -> str:
            payload = json.dumps(data)
            return f"event: {event}\ndata: {payload}\n\n"

        yield sse_msg("run_started", {"run_id": run_id, "as_of": as_of})

        # Phase 1: Start 4 domain agents
        yield sse_msg("phase_started", {"phase": 1, "description": "Running 4 domain agents concurrently"})

        p1_tasks = {
            "network": asyncio.create_task(self.network_agent.run(state, as_of)),
            "airspace_safety": asyncio.create_task(self.airspace_agent.run(state, as_of)),
            "spectrum": asyncio.create_task(self.spectrum_agent.run(state, as_of)),
            "policy_institutional": asyncio.create_task(self.policy_agent.run(state, as_of)),
        }

        agent_reports: dict[str, AgentReport] = {}
        for name, task in p1_tasks.items():
            try:
                rep = await task
                agent_reports[name] = rep
                yield sse_msg("agent_completed", {"agent_name": name, "report": rep.model_dump()})
            except Exception as e:
                logger.error("Streaming error in %s: %s", name, e)
                fallback = AgentReport(agent_name=name, error=str(e), confidence=0.1)
                agent_reports[name] = fallback
                yield sse_msg("agent_completed", {"agent_name": name, "report": fallback.model_dump()})

        # Merge candidate actions
        all_candidate_actions = list(candidate_actions)
        seen_action_ids = {a.id for a in all_candidate_actions}
        for rep in agent_reports.values():
            for act in rep.candidate_actions:
                if act.id not in seen_action_ids:
                    all_candidate_actions.append(act)
                    seen_action_ids.add(act.id)
                else:
                    self._merge_action_metadata(all_candidate_actions, act)

        # Phase 2: Optimization
        yield sse_msg("phase_started", {"phase": 2, "description": "Optimization and Pareto evaluation"})
        try:
            opt_report = await self.opt_agent.run(state, as_of)
            agent_reports["optimization"] = opt_report
            yield sse_msg("agent_completed", {"agent_name": "optimization", "report": opt_report.model_dump()})
            for act in opt_report.candidate_actions:
                if act.id not in seen_action_ids:
                    all_candidate_actions.append(act)
                    seen_action_ids.add(act.id)
                else:
                    self._merge_action_metadata(all_candidate_actions, act)
        except Exception as e:
            opt_report = AgentReport(agent_name="optimization", error=str(e), confidence=0.1)
            agent_reports["optimization"] = opt_report
            yield sse_msg("agent_completed", {"agent_name": "optimization", "report": opt_report.model_dump()})

        # Phase 3: Arbitration
        yield sse_msg("phase_started", {"phase": 3, "description": "Deterministic constraint arbitration"})
        arb_report = await self.arb_agent.arbitrate(
            state=state,
            candidate_actions=all_candidate_actions,
            agent_reports=agent_reports,
            as_of=as_of,
        )

        yield sse_msg("arbitration_completed", {"arbitration": arb_report.model_dump()})

        total_latency = time.time() - start_t
        result = RunResult(
            run_id=run_id,
            scenario_id=scenario_id,
            as_of=as_of,
            simulation_state=state,
            agent_reports=agent_reports,
            arbitration=arb_report,
            candidate_actions=all_candidate_actions,
            total_latency_s=round(total_latency, 3),
        )

        self._write_audit_log(result)
        yield sse_msg("run_finished", {"run_result": result.model_dump()})

    @staticmethod
    def _infer_scenario_id(state: SimulationState) -> str:
        """Keep direct callers compatible while identifying the bundled demos."""
        if (
            state.aircraft.phase == "cat_iii_autoland"
            and state.aircraft.ra_tolerant == "non_tolerant"
        ):
            return "DEMO-003"
        if (
            state.aircraft.phase == "landing_flare"
            and state.cell.distance_to_runway_threshold_m <= 500
        ):
            return "DEMO-002"
        return "DEMO-001"

    @staticmethod
    def _merge_action_metadata(
        actions: list[CandidateAction], generated: CandidateAction
    ) -> None:
        """Preserve caller actions while carrying computed metadata onto them."""
        existing = next((action for action in actions if action.id == generated.id), None)
        if existing is None:
            return
        if generated.simulated_margin_db is not None:
            existing.simulated_margin_db = generated.simulated_margin_db
        if generated.margin_label:
            existing.margin_label = generated.margin_label
        for evidence_id in generated.evidence_ids:
            if evidence_id not in existing.evidence_ids:
                existing.evidence_ids.append(evidence_id)

    def _write_audit_log(self, result: RunResult) -> None:
        try:
            RUNS_DIR.mkdir(parents=True, exist_ok=True)
            log_file = RUNS_DIR / f"{result.run_id}.json"
            log_file.write_text(result.model_dump_json(indent=2), encoding="utf-8")
            logger.info("Audit log written to %s", log_file)
        except Exception as e:
            logger.error("Failed to write audit log: %s", e)


# Global singleton
orchestrator = Orchestrator()
